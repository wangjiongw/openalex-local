"""Generate a tiny synthetic snapshot for local/CI end-to-end checks (no real papers)."""
import argparse
import gzip
import json
from pathlib import Path

from .config import ENTITIES


def make_snapshot(target, legacy=False):
    target = Path(target)
    if target.exists() and any(target.iterdir()):
        raise ValueError('demo target must be empty')
    institution = dict(id='https://openalex.org/I1', display_name='Example Institute', display_name_alternatives=['Demo University'], country_code='US', type='education', works_count=12)
    author = dict(id='https://openalex.org/A1', display_name='Example Researcher', display_name_alternatives=['Demo Scientist'], last_known_institutions=[institution])
    source = dict(id='https://openalex.org/S1', display_name='Geology', type='journal', issn_l='0091-7613', issn=['0091-7613'], works_count=100)
    topic = dict(id='https://openalex.org/T1', display_name='Geology and tectonics', score=.9,
                 field=dict(id='https://openalex.org/fields/19', display_name='Earth and Planetary Sciences'),
                 subfield=dict(id='https://openalex.org/subfields/1907', display_name='Geology'),
                 domain=dict(id='https://openalex.org/domains/3', display_name='Physical Sciences'))
    works = []
    for number in range(1, 13):
        works.append(dict(id='https://openalex.org/W' + str(number), doi='https://doi.org/10.99999/demo.' + str(number),
            title='Climate geology syntheticpaper' + str(number), publication_year=2020 + number % 5,
            publication_date=str(2020 + number % 5) + '-01-01', type='article', language='en', is_xpac=False,
            cited_by_count=1 if number < 12 else 0,
            authorships=[dict(author=author, author_position='first', institutions=[institution])],
            topics=[topic], primary_topic=topic, concepts=[], keywords=[dict(id='https://openalex.org/keywords/geology', display_name='Geology', score=.9)],
            primary_location=dict(source=source, is_published=True, version='publishedVersion'),
            locations=[dict(source=source, is_published=True, version='publishedVersion')],
            open_access=dict(is_oa=bool(number % 2), oa_status='gold' if number % 2 else 'closed'),
            abstract_inverted_index={'Climate': [0], 'geology': [1], '测试': [2]},
            referenced_works=[] if number == 1 else ['https://openalex.org/W' + str(number - 1), 'https://openalex.org/W99999'],
            related_works=['https://openalex.org/W1'] if number != 1 else [],
            unknown_future_field=dict(preserved='yes')))
    records = {entity: [] for entity in ENTITIES}
    records.update(works=works, authors=[author], institutions=[institution], sources=[source], topics=[topic],
                   fields=[topic['field'] | dict(domain=topic['domain'])],
                   subfields=[topic['subfield'] | dict(field=topic['field'],domain=topic['domain'])], domains=[topic['domain']])
    base = target / ('data' if legacy else 'data/jsonl')
    manifests = []
    for entity, values in records.items():
        directory = base / entity
        directory.mkdir(parents=True, exist_ok=True)
        files = []
        if values:
            path = directory / 'updated_date=2026-01-01/part_0000.gz'
            path.parent.mkdir()
            with gzip.open(path, 'wt', encoding='utf-8') as stream:
                for record in values:
                    stream.write(json.dumps(record, ensure_ascii=False) + '\n')
            files.append(dict(url='s3://openalex/data/' + ('' if legacy else 'jsonl/') + entity + '/updated_date=2026-01-01/part_0000.gz',
                              meta=dict(content_length=path.stat().st_size, record_count=len(values))))
        value = dict(entity=entity, format='jsonl', record_count=len(values), content_length=sum(v['meta']['content_length'] for v in files))
        if legacy:
            (directory / 'manifest').write_text(json.dumps(dict(entries=files)))
        else:
            value['files'] = files
            (directory / 'manifest.json').write_text(json.dumps(value))
        manifests.append(value)
    if not legacy:
        (base / 'manifest.json').write_text(json.dumps(dict(date='2026-01-01', format='jsonl', entities=manifests, snapshot_subset=True)))
    (target / 'RELEASE_NOTES.txt').write_text('RELEASE 2026-01-01\nSynthetic local test fixture; not an OpenAlex release.\n')
    (target / 'LICENSE.txt').write_text('Synthetic fixture generated by MIT-licensed OpenAlex Local code.\n')
    return str(target)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('target', type=Path)
    parser.add_argument('--legacy', action='store_true')
    args = parser.parse_args()
    print(make_snapshot(args.target, args.legacy))
